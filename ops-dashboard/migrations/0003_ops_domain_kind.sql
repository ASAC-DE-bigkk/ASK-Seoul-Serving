-- 분야 등록부에 **종류**를 더한다 — 데이터 분야인가, 파이프라인 자체의 작업인가 (#162 🅕)
--
-- ── 왜 필요한가 ────────────────────────────────────────────────────────────────
-- `_ops_domain` 에는 지금 일곱 행이 있는데 그중 `common` 은 **데이터 분야가 아니다.**
-- 관측 기록을 나르는 작업 자체다(`common_ops_d1_load`·`common_ops_logship`).
-- 그런데 화면은 등록부 행 수를 그대로 세므로 **"분야 7개"** 라고 말한다 — 실제 데이터
-- 분야는 여섯이다. 라벨만 '파이프라인 운영 지표'로 바꿔 둔 상태(#162)라 **사람은 읽어서
-- 알지만 숫자는 여전히 틀린다.**
--
-- #162 에서 파이프라인 담당(@yooseongjin527)이 🅕 를 지지하며 못 박은 것이 근거다:
--   "`domain='common'` 은 **원천에서 맞는 값이다.** 업스트림을 고치면 파이프라인이
--    자기 자신에 대해 거짓말을 하게 된다. 콘솔이 표시만 가르면 된다."
-- 즉 **DAG·dbt 는 건드리지 않는다.** 가르는 일은 콘솔 소유 표인 여기서 한다.
--
-- ── 왜 컬럼인가(값 규약이 아니라) ────────────────────────────────────────────
-- `domain='common'` 을 코드에 박아 거를 수도 있었다. 그러면 다음에 파이프라인이
-- `common` 말고 다른 운영 축을 하나 더 만들 때 **콘솔을 고쳐야 화면이 맞는다** — 등록부가
-- 정본인데 정본이 못 말하는 사실이 생긴다. 컬럼이면 등록부 한 줄로 끝난다.
--
-- ── 기본값이 1 인 이유 ───────────────────────────────────────────────────────
-- 새로 들어오는 분야는 **데이터 분야로 본다.** 여기가 압도적 다수고, 빠뜨렸을 때
-- "데이터 분야인데 안 세는" 쪽(지표가 조용히 작아짐)보다 "운영 축인데 세는" 쪽
-- (한 줄 더 보임)이 눈에 띄어서 고쳐진다.
--
-- 증분 규약(decision/0007) — DROP 없음, ALTER 추가 파일로만.
ALTER TABLE _ops_domain ADD COLUMN is_data_domain INTEGER NOT NULL DEFAULT 1;
