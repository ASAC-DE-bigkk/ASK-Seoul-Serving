-- 분야 등록부 (`_ops_domain`) — 화면이 분야를 **한글로 부르는 정본**.
--
-- 콘솔 소유 표다(CLAUDE.md §6). 화면의 `domLabel()` 이 여기서 라벨을 읽고, 없으면 분야
-- 코드를 그대로 쓴다 — **화면은 라벨을 지어내지 않는다.** 그래서 이 표가 비면 운영 화면에
-- `culture`·`commerce` 같은 영문 슬러그가 그대로 노출된다(CLAUDE.md §5 위반).
--
-- ── 왜 파일을 따로 뺐나 ──────────────────────────────────────────────────────────
-- 등록부는 원래 `slo_live.sql`·`slo_sample.sql` **안에** 들어 있었다. 그런데 그 둘은 맨 앞에서
-- `DELETE FROM _ops_slo` 를 한다 — 즉 **등록부만 채우려 해도 SLO 를 건드려야 했다.**
-- 운영 D1 하나뿐인 지금(0015) `slo_sample.sql` 은 합성이라 못 돌리고(운영 오염),
-- `slo_live.sql` 은 발행 실측을 손으로 싣는 것이라 0005 의 폐기된 임시 로더 경로다.
-- **그래서 아무도 못 돌렸고, 운영 등록부가 0행인 채로 남았다**(실측 2026-08-06 · 08-07).
-- 등록부는 표본도 측정값도 아니라 **참조 내용**이므로, 자기 파일로 두면 언제든 안전하게 돈다.
--
-- ── 다시 돌려도 안전하다 ────────────────────────────────────────────────────────
-- `INSERT OR REPLACE` 다. `DELETE` 를 앞에 두지 않는 이유가 둘:
--   ① 지웠다 넣는 사이 화면이 라벨을 잃는다 — 운영 화면이라 그 창을 만들지 않는다.
--   ② **퇴역한 분야의 라벨도 남겨야 한다.** 실행 기록은 개명·폐지보다 오래 살아서, 라벨을
--      지우면 옛 기록이 화면에서 다시 영문 코드가 된다(route 값과 같은 이유 — 0014 §1-1).
--      분야를 정말 지울 일이 생기면 그때 `DELETE` 한 줄을 명시적으로 쓴다.
--
-- 적용:  npm run d1 -- --file=fixtures/ops_domain.sql
-- 확인:  npm run d1 -- "SELECT domain,label,has_slo FROM _ops_domain ORDER BY domain"

-- `has_slo` 는 실측이다 — ASAC-DBT 에서 `*_slo_daily` 모델을 전수 검색해 culture 만 존재.
-- 1 이면 '품질 기준(SLO)' 카드가 그 분야를 센다. 나머지는 기준 자체가 아직 없는 것이지
-- 품질이 나쁜 게 아니다 — `note` 가 화면에서 그렇게 말한다.
INSERT OR REPLACE INTO _ops_domain (domain,label,has_slo,note) VALUES
  ('culture' ,'문화·행사',1,NULL),
  ('citydata','인구·도시',0,'품질 측정 기준이 아직 없음'),
  ('transit' ,'대중교통' ,0,'품질 측정 기준이 아직 없음'),
  ('commerce','상권'     ,0,'품질 측정 기준이 아직 없음'),
  ('weather' ,'날씨'     ,0,'품질 측정 기준이 아직 없음'),
  ('traffic' ,'교통'     ,0,'품질 측정 기준이 아직 없음');

