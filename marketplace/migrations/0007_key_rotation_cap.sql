-- 계정 기준 재발급(회전) 상한 (#303).
--
-- 회전 자체로는 쿼터 이득이 없다 — 당일 사용량을 새 해시로 이월하기 때문이다. 그래도
-- 계정 기준 상한이 없으면 IP 상한(`ISSUE_HOURLY_CAP`)만 남는데, 그건 **공유 IP 에서 남의
-- 몫을 갉아먹는다** — 한 사람이 반복 회전하면 같은 사무실·학교의 다른 사람이 발급을 못 한다.
-- 그래서 "하루 N회"는 계정에 걸어야 맞다.
--
-- 🔴 **새 표가 아니라 `_keys` 의 컬럼인 이유**: 계정을 가리키는 식별자를 새로 저장하지 않기
--    위해서다. 별도 로그 표로 세려면 이메일 해시 같은 값을 또 남겨야 하고, 그러면 개인정보
--    처리방침에 적을 항목이 하나 는다. 카운터는 **이미 있는 그 행**에 붙이면 새로 저장되는
--    개인정보가 0 이다.
--
-- ⚠️ 0006 이 *"`_keys` 에 ALTER 로 섞으면 부분 적용이 사용자 전체 인증 장애가 될 수 있다"*
--    고 적어 두었다. 그 우려는 여기선 두 겹으로 막힌다:
--      ① `deploy:prod` 가 `preflight --require-applied` 로 **미적용 시 배포를 거부**한다
--      ② `authenticate()` 는 명시 컬럼만 읽는다(`key_hash·key_prefix·email·status·daily_quota`)
--         — 이 두 컬럼은 회전 경로에서만 읽히므로 인증 경로에 닿지 않는다
--    0006 이 표를 나눈 진짜 이유는 **다른 종류의 주체**(service key)를 한 표에 섞지 않으려던
--    것이고, 여기는 같은 주체의 카운터다.
--
-- 날짜는 KST 하루 경계(`kstDay()`)를 쓴다 — 쿼터·파이프라인 시간축과 같은 규약.
-- 카운터는 그날 첫 회전에서 1 로 리셋되므로 청소가 필요 없다.
ALTER TABLE _keys ADD COLUMN rotated_day TEXT;
ALTER TABLE _keys ADD COLUMN rotated_count INTEGER NOT NULL DEFAULT 0;
